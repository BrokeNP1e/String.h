char *s21_strerror(int errnum) {
  char *result = s21_NULL;
  if (errnum >= 0 &&
      errnum < (int)(sizeof(s21_errors) / sizeof(s21_errors[0]))) {
    result = (char *)s21_errors[errnum];
  } else {
    static char buffer[256];
    s21_sprintf(buffer, "Unknown error: %d", errnum);
    result = buffer;
  }
  return result;
}